"""pipecat-quickstart - Pipecat voice agent.

Cascaded pipeline: Speech-to-Text -> LLM -> Text-to-Speech.

Generated by the official Pipecat CLI, with a small set of deliberate changes
(see README.md "changes vs. the official template").

Services used:
- Whisper / SenseVoice (Speech-to-Text)  local, no key
- OpenAI-compatible LLM (ModelScope / SenseNova / Suanli)  needs a key
- Piper (Text-to-Speech)  local, no key

Run:
    uv run bot.py

Logs (one run is enough to see the whole frontend+backend flow):
    logs/bot-<timestamp>.log   full DEBUG log of this run
    logs/bot-latest.log        fixed name, always points at the latest run
"""

